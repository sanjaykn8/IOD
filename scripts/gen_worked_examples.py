#!/usr/bin/env python3
"""Render docs/worked-examples.md from the deterministic walkthroughs (python-service/src/learn).

Usage (Linux/macOS):  python3 scripts/gen_worked_examples.py
       (Windows):     python scripts\\gen_worked_examples.py
The document is generated, so every number in it is exactly what the workbench UI shows.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python-service", "src"))

from learn import fixtures as F  # noqa: E402
from learn.walkthrough import WALKTHROUGHS, walkthrough  # noqa: E402


def cell(v):
    return str(v).replace("|", "/")


def matrix_md(name, data):
    rows = data if data and isinstance(data[0], list) else [data]
    out = [f"*{name}*", "", "| " + " | ".join([""] * len(rows[0])) + " |", "|" + "---|" * len(rows[0])]
    out += ["| " + " | ".join(cell(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    lines = ["# Worked numerical examples (generated)", "",
             "> Generated by `scripts/gen_worked_examples.py` from `python-service/src/learn/walkthrough.py`. "
             "Do not edit by hand. Educational material only - these calculations never take part in a UAV transmission.", "",
             "Fixtures used everywhere:", "",
             f"* 8x8 hand matrix (the classic JPEG tutorial luminance block): `{F.HAND_MATRIX.tolist()}`",
             f"* Synthetic ciphertext fixture: `{F.SYNTHETIC_CIPHERTEXT.hex(' ').upper()}` - {F.SYNTHETIC_LABEL}",
             f"* Bit order: {F.BIT_ORDER} (`A6` -> `10100110`)", ""]
    for name in WALKTHROUGHS:
        d = walkthrough(name)
        lines += [f"## {d['title']} (`{name}`)", "", f"Runtime variant: `{d['runtime_variant']}`", ""]
        if d["teaching_model"]:
            lines += [f"> **Teaching model.** {d['simplification']}", ""]
        for s in d["steps"]:
            lines += [f"**Step {s['n']} - {s['title']}**", "", f"* Formula: `{s['formula']}`",
                      f"* Substituted values: `{s['substitution']}`", f"* Result: `{s['result']}`"]
            if s.get("note"):
                lines.append(f"* Note: {s['note']}")
            lines.append("")
            if s.get("table"):
                t = s["table"]
                lines += ["| " + " | ".join(t["columns"]) + " |", "|" + "---|" * len(t["columns"])]
                lines += ["| " + " | ".join(cell(x) for x in r) + " |" for r in t["rows"]]
                lines.append("")
            for k, v in (s.get("matrices") or {}).items():
                lines += [matrix_md(k, v), ""]
        checks = ", ".join(f"{c['name']}: {'pass' if c['passed'] else 'FAIL'}" for c in d["checks"])
        lines += [f"Embedded `{d['embedded_bits']}` -> recovered `{d['recovered_bits']}` - exact match: **{d['exact_match']}**. "
                  f"Checks: {checks}.", "", f"*Runtime link:* {d['runtime_link']}", ""]
    path = os.path.join(ROOT, "docs", "worked-examples.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
